#!/usr/bin/env bash
# Install the McStas 1D Monitor Plotter into a conda environment
# (Linux / macOS).
#
#   ./install.sh                 # creates/updates env "mcstas-plotter"
#   ./install.sh my-env-name     # use a different environment name
#
set -euo pipefail

ENV_NAME="${1:-mcstas-plotter}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Prefer mamba (faster) if available, else conda.
if command -v mamba >/dev/null 2>&1; then
    SOLVER=mamba
elif command -v conda >/dev/null 2>&1; then
    SOLVER=conda
else
    echo "ERROR: neither 'conda' nor 'mamba' was found on PATH." >&2
    echo "Install Miniforge first: https://conda-forge.org/download/" >&2
    echo "then open a new terminal (or run 'source ~/miniforge3/bin/activate')" >&2
    echo "and re-run this script." >&2
    exit 1
fi
command -v conda >/dev/null 2>&1 || { echo "ERROR: 'conda' not on PATH." >&2; exit 1; }

echo ">>> Using $SOLVER to set up environment '$ENV_NAME'"
if conda env list | awk '{print $1}' | grep -qx "$ENV_NAME"; then
    echo ">>> Environment exists - updating"
    "$SOLVER" env update -n "$ENV_NAME" -f "$HERE/environment.yml" --prune
else
    echo ">>> Creating environment"
    "$SOLVER" env create -n "$ENV_NAME" -f "$HERE/environment.yml"
fi

# Locate the environment's python. First from 'conda env list'
# (name ... path), then fall back to asking the environment itself,
# ignoring any blank/extra lines conda prints.
PYEXE=""
ENV_PREFIX="$(conda env list | awk -v n="$ENV_NAME" '$1 == n {print $NF}' | head -n 1)"
if [ -n "$ENV_PREFIX" ] && [ -x "$ENV_PREFIX/bin/python" ]; then
    PYEXE="$ENV_PREFIX/bin/python"
else
    PYEXE="$(conda run -n "$ENV_NAME" python -c 'import sys; print("PYEXE=" + sys.executable)' 2>/dev/null \
             | tr -d '\r' | sed -n 's/^PYEXE=//p' | tail -n 1)"
fi
if [ -z "$PYEXE" ] || [ ! -x "$PYEXE" ]; then
    echo "ERROR: could not locate python in environment '$ENV_NAME'." >&2
    echo "Check with:  conda env list" >&2
    exit 1
fi
echo ">>> Environment python: $PYEXE"

echo ">>> Checking packages"
"$PYEXE" -c "import numpy, matplotlib, PySide6; print('numpy', numpy.__version__, '| matplotlib', matplotlib.__version__, '| PySide6', PySide6.__version__)"

# Launcher that runs the app with the environment's python directly
LAUNCHER="$HERE/run_plotter.sh"
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Launch the McStas 1D Monitor Plotter (generated by install.sh)
exec "$PYEXE" "$HERE/mcstas_plotter.py" "\$@"
EOF
chmod +x "$LAUNCHER" "$HERE/mcstas_plotter.py"

# Optional example data
if [ ! -d "$HERE/example_data" ]; then
    "$PYEXE" "$HERE/make_example_data.py" "$HERE/example_data" >/dev/null && \
        echo ">>> Example data written to $HERE/example_data"
fi

echo
echo "Installation complete."
echo "Start the plotter with:"
echo "    $LAUNCHER [data_folder]"
echo "or:"
echo "    conda activate $ENV_NAME && python $HERE/mcstas_plotter.py [data_folder]"
